using System.Reflection;
using System.Text;
using BlitzCS.BinaryCompiler;
using BlitzCS.BinaryCompiler.Runtime;
using BlitzCS.Compiler;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace BlitzCS.CLI;

/// <summary>A catalog function bound directly to an export of a PE32 library (<c>"binary"</c> entry).</summary>
internal sealed record BinaryBinding(string BasicName, string LibraryPath, string Export, GuestCallingConvention Convention,
    IReadOnlyList<ExternalValueType> Parameters, ExternalValueType ReturnType, bool LibraryDefaultCdecl = false)
{
    /// <summary>Convention passed to the runtime: declared, else decoration (left Unknown for the runtime), else the library's cdecl default.</summary>
    internal string? Intrinsic { get; init; }
    internal IReadOnlyList<bool>? PointerParameters { get; init; }
    internal int? ExportArgCount { get; init; }
    internal uint? CommandRva { get; init; }
    /// <summary>SHA-256 of a verified native 32-bit Blitz3D runtime command library.</summary>
    internal string? NativeCommandSha256 { get; init; }
    internal string? Win32SystemDll { get; init; }
    internal bool FromUserLib { get; init; }

    internal GuestCallingConvention Generated => Convention != GuestCallingConvention.Unknown ? Convention
        : LibraryDefaultCdecl && ExportAbiHints.Infer(Export).Convention == GuestCallingConvention.Unknown ? GuestCallingConvention.Cdecl : Convention;
}

/// <summary>Generates and compiles the managed binding assembly for catalog 'binary' functions. Contains no library-specific code.</summary>
internal static class BinaryBindingGenerator
{
    internal const string AssemblyName = "BlitzCS.BinaryBindings";
    internal const string Namespace = "BlitzCS.BinaryBindings";

    /// <summary>Compiles the bindings into <paramref name="stagingDirectory"/> (with the runtime assemblies the bindings load) and returns the assembly path.</summary>
    internal static string Generate(IReadOnlyList<BinaryBinding> bindings, IReadOnlyList<BinaryLibrarySpec> specs, string stagingDirectory)
    {
        var runtimeAssembly = typeof(BinaryLibrary).Assembly;
        CopyRuntimeClosure(runtimeAssembly, stagingDirectory);
        var useWin32 = UsesWin32(specs) || bindings.Any(b => b.Win32SystemDll is not null);
        if (useWin32) CopyRuntimeClosure(typeof(BlitzCS.BinaryCompiler.Win32.Win32ImportResolver).Assembly, stagingDirectory);
        var source = Source(bindings, specs);
        var platform = (string?)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")
            ?? throw new InvalidOperationException("The host runtime does not expose platform references.");
        var references = platform.Split(Path.PathSeparator)
            .Concat([runtimeAssembly.Location, typeof(GuestCallingConvention).Assembly.Location])
            .Concat(useWin32 ? [typeof(BlitzCS.BinaryCompiler.Win32.Win32ImportResolver).Assembly.Location] : [])
            .Distinct(StringComparer.Ordinal).Select(path => MetadataReference.CreateFromFile(path));
        var compilation = CSharpCompilation.Create(AssemblyName,
            [CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.CSharp14))], references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, optimizationLevel: OptimizationLevel.Release, deterministic: true));
        var target = Path.Combine(stagingDirectory, AssemblyName + ".dll");
        using var stream = new MemoryStream();
        var result = compilation.Emit(stream);
        if (!result.Success)
            throw new InvalidOperationException("Binary binding generation failed: " + string.Join(Environment.NewLine,
                result.Diagnostics.Where(d => d.Severity == Microsoft.CodeAnalysis.DiagnosticSeverity.Error)));
        File.WriteAllBytes(target, stream.ToArray());
        return target;
    }

    internal static string TypeName(int libraryIndex) => $"{Namespace}.Library{libraryIndex}";
    internal static string MethodName(string basicName) => "Fn_" + basicName;

    internal static IReadOnlyList<string> Libraries(IReadOnlyList<BinaryBinding> bindings) =>
        bindings.Select(b => b.LibraryPath).Distinct(StringComparer.Ordinal).ToArray();

    internal static bool UsesWin32(IReadOnlyList<BinaryLibrarySpec> specs) => specs.Any(spec => spec.Win32 != false);

    internal static string Source(IReadOnlyList<BinaryBinding> bindings, IReadOnlyList<BinaryLibrarySpec> specs)
    {
        const string rt = "global::BlitzCS.BinaryCompiler.Runtime.";
        var text = new StringBuilder("// <auto-generated/>\nnamespace " + Namespace + ";\n");
        var libraries = Libraries(bindings);
        var useWin32 = UsesWin32(specs) || bindings.Any(b => b.Win32SystemDll is not null);
        if (useWin32)
        {
            text.Append($"internal sealed class Win32Environment : {rt}IBinaryHostEnvironment\n{{\n"
                + "    private readonly global::System.Func<string, " + rt + "IGuestImportResolver> factory;\n"
                + "    private readonly global::System.Lazy<global::BlitzCS.BinaryCompiler.Win32.Win32ImportResolver> defaultResolver;\n\n"
                + "    public Win32Environment(bool appFiles, global::BlitzCS.BinaryCompiler.Win32.WaveOutBackendKind audio, string? audioRecord)\n    {\n"
                + "        var options = new global::BlitzCS.BinaryCompiler.Win32.Win32Options\n        {\n"
                + "            SandboxRoot = appFiles ? global::System.IO.Path.GetDirectoryName(typeof(Win32Environment).Assembly.Location) : null,\n"
                + "            WaveOut = audio,\n"
                + "            WaveOutRecordPath = audioRecord is null ? null : global::System.IO.Path.Combine(global::System.IO.Path.GetDirectoryName(typeof(Win32Environment).Assembly.Location)!, audioRecord),\n"
                + "        };\n"
                + "        factory = global::BlitzCS.BinaryCompiler.Win32.Win32ImportResolver.SharedFactory(options);\n"
                + "        defaultResolver = new global::System.Lazy<global::BlitzCS.BinaryCompiler.Win32.Win32ImportResolver>(() => (global::BlitzCS.BinaryCompiler.Win32.Win32ImportResolver)factory(\"\"));\n"
                + "    }\n\n"
                + $"    public {rt}IGuestImportResolver CreateResolver(string moduleName) => factory(moduleName);\n"
                + "    public global::BlitzCS.BinaryCompiler.Win32.Win32ImportResolver Resolver => defaultResolver.Value;\n"
                + "}\n");
        }
        text.Append("internal static class Registry\n{\n");
        if (useWin32)
        {
            var appFiles = specs.Any(s => s.AppFileRoot) ? "true" : "false";
            var audio = WaveOutKind(specs.FirstOrDefault(s => s.Audio != null)?.Audio);
            var record = specs.FirstOrDefault(s => s.AudioRecord != null)?.AudioRecord;
            var recordLiteral = record is null ? "null" : Literal(record);
            text.Append($"    internal static readonly Win32Environment SharedWin32 = new Win32Environment({appFiles}, {audio}, {recordLiteral});\n");
        }
        for (var k = 0; k < specs.Count; k++)
        {
            var spec = specs[k];
            var conventions = new StringBuilder();
            foreach (var (export, signature) in spec.ExportConventions)
                conventions.Append($"[{Literal(export)}] = {(signature.Convention == GuestCallingConvention.Cdecl ? rt + "ExportSignature.Cdecl" : $"{rt}ExportSignature.Stdcall({signature.ArgCount})")}, ");
            // explicit per-function stdcall/cdecl conventions also tell sibling libraries how to bridge the export
            foreach (var b in bindings.Where(b => b.LibraryPath == spec.Path && b.Convention is GuestCallingConvention.Cdecl or GuestCallingConvention.Stdcall && !spec.ExportConventions.ContainsKey(b.Export)).DistinctBy(b => b.Export))
                conventions.Append($"[{Literal(b.Export)}] = {(b.Convention == GuestCallingConvention.Cdecl ? rt + "ExportSignature.Cdecl" : $"{rt}ExportSignature.Stdcall({b.ExportArgCount ?? b.Parameters.Count})")}, ");
            text.Append($"    internal static readonly {rt}BinaryLibrary L{k} = {rt}BinaryLibrary.For(typeof(Registry).Assembly, {Literal(spec.FileName)}, new {rt}BinaryLibraryOptions\n    {{\n");
            if (spec.Win32 != false || useWin32) text.Append($"        Environment = SharedWin32, EnvironmentRequired = {(spec.Win32 == true ? "true" : "false")},\n");
            text.Append($"        RunEntryPoint = {(spec.RunEntryPoint ? "true" : "false")}, AllowUnboundImports = {(spec.UnboundImportsAreErrors ? "false" : "true")},\n");
            if (spec.DefaultCdecl || conventions.Length > 0)
                text.Append($"        Conventions = new {rt}ExportConventions {{ {(spec.DefaultCdecl ? "Default = global::BlitzCS.BinaryCompiler.GuestCallingConvention.Cdecl, " : "")}Exports = new global::System.Collections.Generic.Dictionary<string, {rt}ExportSignature> {{ {conventions}}} }},\n");
            text.Append("    });\n");
        }
        text.Append("}\n");
        for (var l = 0; l < libraries.Count; l++)
        {
            text.Append($"public static class Library{l}\n{{\n");
            var members = bindings.Where(b => b.LibraryPath == libraries[l]).ToArray();
            var nativeCommands = members.Where(b => b.NativeCommandSha256 is not null).ToArray();
            if (nativeCommands.Length > 0)
            {
                if (nativeCommands.Length != members.Length || nativeCommands.Any(b => b.NativeCommandSha256 != nativeCommands[0].NativeCommandSha256))
                    throw new InvalidOperationException($"Library '{Path.GetFileName(libraries[l])}' mixes native Blitz3D commands with another binding type or runtime version.");
                text.Append($"    private static readonly {rt}NativeBlitzCommandLibrary Lib = {rt}NativeBlitzCommandLibrary.For(typeof(Registry).Assembly, {Literal(Path.GetFileName(libraries[l]))}, {Literal(nativeCommands[0].NativeCommandSha256!)});\n");
            }
            else
            {
                text.Append($"    private static readonly {rt}BinaryLibrary Lib = Registry.L{IndexOfSpec(specs, libraries[l])};\n");
            }
            for (var m = 0; m < members.Length; m++)
            {
                var b = members[m];
                if (b.Intrinsic is { } op)
                {
                    var name = char.ToUpperInvariant(op[0]) + op[1..];
                    var ps = string.Join(", ", b.Parameters.Select((_, i) => $"int a{i}"));
                    var args = string.Join(", ", b.Parameters.Select((_, i) => $"a{i}"));
                    text.Append(b.ReturnType == ExternalValueType.Void
                        ? $"    public static void {MethodName(b.BasicName)}({ps}) => Lib.{name}({args});\n"
                        : $"    public static int {MethodName(b.BasicName)}({ps}) => Lib.{name}({args});\n");
                    continue;
                }

                if (b.CommandRva is { } rva)
                {
                    var commandType = b.NativeCommandSha256 is null ? "BinaryCommandExport" : "NativeBlitzCommandExport";
                    text.Append($"    private static readonly {rt}{commandType} C{m} = Lib.Command(0x{rva:X}u, {Literal(b.BasicName)}, {b.Parameters.Count});\n");
                    var parameters = string.Join(", ", b.Parameters.Select((p, i) => $"{ClrType(p)} a{i}"));
                    var cmdArgs = string.Join(", ", b.Parameters.Select((p, i) =>
                    {
                        if (b.PointerParameters is not null && i < b.PointerParameters.Count && b.PointerParameters[i])
                            return $"{rt}BinaryArgument.FromPointer(a{i})";
                        return $"{rt}BinaryArgument.From{p switch { ExternalValueType.Integer => "Int32", ExternalValueType.Float => "Single", _ => "String" }}(a{i})";
                    }));
                    text.Append(b.ReturnType switch
                    {
                        ExternalValueType.Void => $"    public static void {MethodName(b.BasicName)}({parameters}) {{ C{m}.Call({cmdArgs}); }}\n",
                        ExternalValueType.Float => $"    public static float {MethodName(b.BasicName)}({parameters}) => C{m}.CallSingle({cmdArgs});\n",
                        ExternalValueType.String => $"    public static string {MethodName(b.BasicName)}({parameters}) => C{m}.CallString({cmdArgs});\n",
                        _ => $"    public static int {MethodName(b.BasicName)}({parameters}) => (int)C{m}.Call({cmdArgs});\n",
                    });
                    continue;
                }

                if (b.Win32SystemDll is { } sysDll)
                {
                    var parameters = string.Join(", ", b.Parameters.Select((p, i) => $"{ClrType(p)} a{i}"));
                    var returnTypeStr = b.ReturnType switch
                    {
                        ExternalValueType.Void => "void",
                        ExternalValueType.Float => "float",
                        ExternalValueType.String => "string",
                        _ => "int"
                    };
                    text.Append($"    public static {returnTypeStr} {MethodName(b.BasicName)}({parameters})\n    {{\n");
                    text.Append("        var mod = Lib.EnsureOpen();\n");
                    text.Append("        var mem = mod.Memory;\n");
                    text.Append($"        global::System.Collections.Generic.List<{rt}GuestBuffer>? buffers = null;\n");
                    text.Append($"        global::System.Collections.Generic.List<({rt}GuestBuffer Buffer, int Length, global::System.Action<byte[]> WriteBack)>? writeBacks = null;\n");
                    text.Append("        try\n        {\n");
                    text.Append($"            var words = new uint[{b.Parameters.Count}];\n");
                    for (var i = 0; i < b.Parameters.Count; i++)
                    {
                        var p = b.Parameters[i];
                        var isPtr = b.PointerParameters is not null && i < b.PointerParameters.Count && b.PointerParameters[i];
                        var argExpr = isPtr ? $"{rt}BinaryArgument.FromPointer(a{i})"
                            : $"{rt}BinaryArgument.From{p switch { ExternalValueType.Integer => "Int32", ExternalValueType.Float => "Single", _ => "String" }}(a{i})";
                        text.Append($"            words[{i}] = {rt}BinaryLibrary.MarshalArgument(Lib, mem, {argExpr}, ref buffers, ref writeBacks, allowStringBankCoercion: true);\n");
                    }
                    text.Append($"            var result = Registry.SharedWin32.Resolver.Call(mem, {Literal(sysDll)}, {Literal(b.Export)}, words);\n");
                    text.Append($"            {rt}BinaryLibrary.CompleteWriteBacks(writeBacks);\n");
                    if (b.ReturnType == ExternalValueType.Void)
                    {
                    }
                    else if (b.ReturnType == ExternalValueType.Float)
                    {
                        text.Append("            return global::System.BitConverter.UInt32BitsToSingle(result);\n");
                    }
                    else if (b.ReturnType == ExternalValueType.String)
                    {
                        text.Append($"            return {rt}BinaryLibrary.ReadAnsiCString(mem, result);\n");
                    }
                    else
                    {
                        text.Append("            return unchecked((int)result);\n");
                    }
                    text.Append("        }\n");
                    text.Append("        finally\n        {\n");
                    text.Append("            if (buffers is not null)\n");
                    text.Append("                foreach (var bfr in buffers) try { bfr.Dispose(); } catch (global::System.Exception) { }\n");
                    text.Append("        }\n");
                    text.Append("    }\n");
                    continue;
                }

                var expArgCount = b.ExportArgCount ?? b.Parameters.Count;
                text.Append($"    private static readonly {rt}BinaryExport E{m} = Lib.Export({Literal(b.Export)}, global::BlitzCS.BinaryCompiler.GuestCallingConvention.{b.Generated}, {expArgCount});\n");
                var stdParams = string.Join(", ", b.Parameters.Select((p, i) => $"{ClrType(p)} a{i}"));
                var argList = new List<string>();
                for (var i = 0; i < b.Parameters.Count; i++)
                {
                    var p = b.Parameters[i];
                    if (b.PointerParameters is not null && i < b.PointerParameters.Count && b.PointerParameters[i])
                        argList.Add($"{rt}BinaryArgument.FromPointer(a{i})");
                    else
                        argList.Add($"{rt}BinaryArgument.From{p switch { ExternalValueType.Integer => "Int32", ExternalValueType.Float => "Single", _ => "String" }}(a{i})");
                }
                for (var i = b.Parameters.Count; i < expArgCount; i++)
                {
                    argList.Add($"{rt}BinaryArgument.FromInt32(0)");
                }
                var arguments = string.Join(", ", argList);
                var call = $"E{m}.Call({arguments})";
                text.Append(b.ReturnType switch
                {
                    ExternalValueType.Void => $"    public static void {MethodName(b.BasicName)}({stdParams}) {{ {call}; }}\n",
                    ExternalValueType.Float => $"    public static float {MethodName(b.BasicName)}({stdParams}) => E{m}.CallSingle({arguments});\n",
                    ExternalValueType.String => $"    public static string {MethodName(b.BasicName)}({stdParams}) => E{m}.CallCString({arguments});\n",
                    _ => $"    public static int {MethodName(b.BasicName)}({stdParams}) => (int){call};\n",
                });
            }
            text.Append("}\n");
        }
        return text.ToString();
    }

    /// <summary>The Win32 component's <c>WaveOutBackendKind</c> a catalog <c>audio</c> value selects (null: its default).</summary>
    private static string WaveOutKind(string? audio) => "global::BlitzCS.BinaryCompiler.Win32.WaveOutBackendKind." + audio switch
    {
        "host" => "HostWinmm", "virtual" => "VirtualSink", "none" => "None", _ => "Default"
    };

    private static int IndexOfSpec(IReadOnlyList<BinaryLibrarySpec> specs, string path)
    {
        for (var i = 0; i < specs.Count; i++) if (specs[i].Path == path) return i;
        throw new InvalidOperationException("Binary library spec not found.");
    }

    private static string ClrType(ExternalValueType type) => type switch
    {
        ExternalValueType.Integer => "int", ExternalValueType.Float => "float", _ => "string"
    };

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    /// <summary>
    /// The shared framework is never part of the closure. In a framework-dependent app its assemblies are not next to the runtime assembly (so the file check
    /// already skipped them); in a self-contained app (the Windows deployment) they are, and copying or loading them from there is wrong.
    /// </summary>
    private static bool IsFrameworkAssembly(string name) =>
        name is "mscorlib" or "netstandard" or "WindowsBase" || name.StartsWith("System.", StringComparison.Ordinal) || name == "System" || name.StartsWith("Microsoft.", StringComparison.Ordinal);

    private static void CopyRuntimeClosure(Assembly root, string stagingDirectory)
    {
        Directory.CreateDirectory(stagingDirectory);
        var directory = Path.GetDirectoryName(root.Location)!;
        var pending = new Queue<Assembly>([root]);
        var seen = new HashSet<string>(StringComparer.Ordinal);
        while (pending.TryDequeue(out var assembly))
        {
            if (!seen.Add(assembly.GetName().Name!)) continue;
            File.Copy(assembly.Location, Path.Combine(stagingDirectory, Path.GetFileName(assembly.Location)), overwrite: true);
            foreach (var reference in assembly.GetReferencedAssemblies())
                if (reference.Name is not null && !IsFrameworkAssembly(reference.Name) && File.Exists(Path.Combine(directory, reference.Name + ".dll")))
                    pending.Enqueue(Assembly.LoadFrom(Path.Combine(directory, reference.Name + ".dll")));
        }
    }
}
