using System.Globalization;
using System.Text;
using System.Text.Json;

namespace BlitzCS.Compiler;

internal static class CSharpEmitter
{
    internal static string Emit(IrProgram program, string sourcePath)
    {
        var output = new StringBuilder("// Generated by BlitzCS.\n");
        foreach (var module in program.Modules)
        {
            Map(output, module.Position, sourcePath);
            output.Append(new string(' ', module.Position.Column - 1)).AppendLine(module.Code);
            output.AppendLine("#line default");
        }
        if (program.Main.Variables.Concat(program.Globals.Select(g => g.Type))
            .Concat(program.Functions.SelectMany(f => f.Scope.Variables))
            .Concat(program.ObjectTypes.SelectMany(t => t.Fields.Values)).Any(t => t.IsVector))
            output.AppendLine(VectorRuntime.Source);
        if (program.ObjectTypes.Count > 0)
        {
            output.AppendLine(ObjectRuntime.Source);
            foreach (var type in program.ObjectTypes)
            {
                output.AppendLine($"internal sealed class __BlitzObject_{type.Name} : __BlitzObject {{");
                foreach (var field in type.Fields) output.AppendLine($"internal {Primitive.CSharp(field.Value)} @{field.Key} = {Primitive.Default(field.Value)};");
                output.AppendLine("internal override void ClearFields() {");
                foreach (var field in type.Fields) output.AppendLine($"@{field.Key} = {(field.Value.IsVector ? "null" : Primitive.Default(field.Value))};");
                output.AppendLine("} }");
            }
            output.AppendLine("internal static class __BlitzObjects {");
            foreach (var type in program.ObjectTypes) output.AppendLine($"internal static readonly __BlitzObjectList<__BlitzObject_{type.Name}> @{type.Name} = new();");
            output.AppendLine("}");
        }
        if (program.Arrays.Count > 0)
        {
            output.AppendLine(ArrayRuntime.Source);
            output.AppendLine("internal static class __BlitzArrays {");
            foreach (var array in program.Arrays)
                output.AppendLine($"    internal static readonly __BlitzArray<{Primitive.CSharp(array.Type)}> {array.Storage[(array.Storage.LastIndexOf('.') + 1)..]} = new({Quote(array.Name)});");
            output.AppendLine("}");
        }
        if (program.UsesData) output.AppendLine(DataRuntime.Emit(program.Data));
        output.AppendLine("public static class BB\n{");
        foreach (var global in program.Globals) output.AppendLine($"    {(global.Type.IsObject || global.Type.IsVector ? "internal" : "public")} static {Primitive.CSharp(global.Type)} @{global.Name} = {Primitive.Default(global.Type)};");
        output.AppendLine(CompatibilityRuntime.Source);
        foreach (var function in program.Functions)
        {
            var parameters = string.Join(", ", Enumerable.Range(0, function.Scope.ParameterCount).Select(i => $"{Primitive.CSharp(function.Scope.Variables[i])} v{i}"));
            Map(output, function.Position, sourcePath);
            output.AppendLine($"    {(function.ReturnType.IsObject || function.Scope.Variables.Take(function.Scope.ParameterCount).Any(t => t.IsObject) ? "internal" : "public")} static {Primitive.CSharp(function.ReturnType)} @{function.Name}({parameters})\n    {{");
            EmitScope(output, function.Scope, sourcePath, true);
            output.AppendLine("    }");
        }
        output.AppendLine("}\ninternal static class BlitzProgram\n{\n    public static void Main()\n    {");
        if (program.Globals.Any(global => global.Type.IsVector))
            output.AppendLine("        System.Runtime.CompilerServices.RuntimeHelpers.RunClassConstructor(typeof(global::BB).TypeHandle);");
        EmitScope(output, program.Main, sourcePath, false);
        return output.AppendLine("    }\n}").ToString();
    }

    private static void Map(StringBuilder output, SourcePosition position, string sourcePath) =>
        output.AppendLine($"#line {position.Line} {Quote(position.File ?? sourcePath)}");

    private static void EmitScope(StringBuilder output, IrScope scope, string sourcePath, bool function)
    {
        output.AppendLine("#line default");
        for (var slot = scope.ParameterCount; slot < scope.Variables.Count; slot++)
            output.AppendLine($"        {Primitive.CSharp(scope.Variables[slot])} v{slot} = {Primitive.Default(scope.Variables[slot])};");
        var temporary = 0;
        var terminated = EmitStatements(output, scope.Statements, sourcePath, function, scope.ReturnType, ref temporary);
        if (function && !terminated) output.AppendLine($"        return {Primitive.Default(scope.ReturnType)};");
    }

    private static bool EmitStatements(StringBuilder output, IReadOnlyList<IrStatement> statements, string sourcePath, bool function, ValueType returnType, ref int temporary)
    {
        var terminated = false;
        foreach (var statement in statements)
        {
            Map(output, statement.Position, sourcePath);
            switch (statement)
            {
                case IrVectorAssign assign: output.AppendLine($"        {EmitVectorAccess(assign.Target)} = {EmitExpression(assign.Value)};"); break;
                case IrFieldAssign assign: output.AppendLine($"        {EmitField(assign.Target)} = {EmitExpression(assign.Value)};"); break;
                case IrDelete delete:
                    output.AppendLine(delete.Value is null ? $"        {ObjectList(delete.ObjectType)}.DeleteEach();" : $"        {ObjectList(delete.ObjectType)}.Delete({EmitExpression(delete.Value)});"); break;
                case IrInsert insert: output.AppendLine($"        {ObjectList(insert.Value.Type)}.Insert({EmitExpression(insert.Value)}, {EmitExpression(insert.Anchor)}, {(insert.Before ? "true" : "false")}, {Quote(insert.Location)});"); break;
                case IrForEach loop:
                    var each = $"e{temporary++}";
                    output.AppendLine($"        for (bool {each} = {ObjectList(loop.ObjectType)}.EachFirst(ref {EmitStorage(loop.Target)}); {each}; {each} = {ObjectList(loop.ObjectType)}.EachNext(ref {EmitStorage(loop.Target)})) {{");
                    EmitStatements(output, loop.Body, sourcePath, function, returnType, ref temporary);
                    output.AppendLine("        }"); break;
                case IrPrint print: output.AppendLine($"        System.Console.WriteLine({(print.Value.Type == ValueType.Float ? $"global::BB.__BlitzString({EmitExpression(print.Value)})" : EmitExpression(print.Value))});"); break;
                case IrDataRead read:
                    var readMethod = read.Target.Type == ValueType.Integer ? "ReadInteger"
                        : read.Target.Type == ValueType.Float ? "ReadFloat" : "ReadString";
                    output.AppendLine($"        {EmitStorage(read.Target)} = global::__BlitzData.{readMethod}({Quote(read.Location)});");
                    break;
                case IrDataRestore restore: output.AppendLine($"        global::__BlitzData.Restore({restore.Index});"); break;
                case IrArrayAssign assign: output.AppendLine($"        {EmitArrayAccess(assign.Target)} = {EmitExpression(assign.Value)};"); break;
                case IrDim dim:
                    // Legacy Dim releases the old array before evaluating any new bound.
                    output.AppendLine($"        {dim.Array.Storage}.Reset();");
                    output.AppendLine($"        {dim.Array.Storage}.Dimension(new int[] {{ {string.Join(", ", dim.Bounds.Select(EmitExpression))} }}, {Quote(dim.Location)});"); break;
                case IrAssign assign: output.AppendLine($"        {assign.Storage} = {EmitExpression(assign.Value)};"); break;
                case IrCallStatement call: output.AppendLine($"        {(call.Value.Type == ValueType.String ? "_ = " : "")}{EmitExpression(call.Value)};"); break;
                case IrReturn ret: output.AppendLine($"        return {EmitExpression(ret.Value)};"); terminated = true; break;
                case IrCSharp code:
                    output.AppendLine("        {");
                    Map(output, code.Position, sourcePath);
                    output.Append(new string(' ', code.Position.Column - 1)).AppendLine(code.Code);
                    output.AppendLine("        }");
                    break;
                case IrIf conditional:
                    output.AppendLine($"        if ({EmitExpression(conditional.Condition)} != 0) {{");
                    EmitStatements(output, conditional.Then, sourcePath, function, returnType, ref temporary);
                    output.AppendLine("        } else {");
                    EmitStatements(output, conditional.Else, sourcePath, function, returnType, ref temporary);
                    output.AppendLine("        }"); break;
                case IrWhile loop:
                    output.AppendLine($"        while ({EmitExpression(loop.Condition)} != 0) {{");
                    EmitStatements(output, loop.Body, sourcePath, function, returnType, ref temporary);
                    output.AppendLine("        }"); break;
                case IrRepeat loop:
                    output.AppendLine("        do {");
                    EmitStatements(output, loop.Body, sourcePath, function, returnType, ref temporary);
                    output.AppendLine(loop.Until is null ? "        } while (true);" : $"        }} while ({EmitExpression(loop.Until)} == 0);"); break;
                case IrFor loop:
                    output.AppendLine($"        for ({EmitStorage(loop.Variable)} = {EmitExpression(loop.From)}; {EmitStorage(loop.Variable)} {(loop.Ascending ? "<=" : ">=")} {EmitExpression(loop.To)}; {EmitStorage(loop.Variable)} = unchecked({EmitStorage(loop.Variable)} + {EmitExpression(loop.Step)})) {{");
                    EmitStatements(output, loop.Body, sourcePath, function, returnType, ref temporary);
                    output.AppendLine("        }"); break;
                case IrSelect selection:
                    var selected = $"s{temporary++}";
                    output.AppendLine($"        {{ {Primitive.CSharp(selection.Value.Type)} {selected} = {EmitExpression(selection.Value)};");
                    var first = true;
                    foreach (var item in selection.Cases)
                    {
                        Map(output, item.Position, sourcePath);
                        var matches = item.Values.Select(value => $"({EmitComparison(selected, selection.Value.Type, TokenKind.Equal, EmitExpression(value))})");
                        output.AppendLine($"        {(first ? "if" : "else if")} ({string.Join(" || ", matches)}) {{");
                        EmitStatements(output, item.Body, sourcePath, function, returnType, ref temporary);
                        output.AppendLine("        }"); first = false;
                    }
                    output.AppendLine(first ? "        {" : "        else {");
                    EmitStatements(output, selection.Default, sourcePath, function, returnType, ref temporary);
                    output.AppendLine("        } }"); break;
                case IrExit: output.AppendLine("        break;"); break;
                case IrEnd:
                    if (function) output.AppendLine($"        System.Environment.Exit(0);\n        return {Primitive.Default(returnType)};");
                    else output.AppendLine("        return;");
                    terminated = true; break;
            }
            output.AppendLine("#line default");
        }
        return terminated;
    }

    // JSON string escaping is also valid for the C# literals used here.
    private static string Quote(string value) => JsonSerializer.Serialize(value, new JsonSerializerOptions
    {
        Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping
    });

    private static string EmitExpression(IrExpression expression) => expression switch
    {
        IrObjectOperation operation => EmitObject(operation),
        IrVectorAccess access => access.Type == ValueType.String ? $"({EmitVectorAccess(access)} ?? \"\")" : EmitVectorAccess(access),
        IrField field => field.Type == ValueType.String ? $"({EmitField(field)} ?? \"\")" : EmitField(field),
        IrInteger integer => integer.Value.ToString(CultureInfo.InvariantCulture),
        IrFloat floating => FloatLiteral.Emit(floating.Value),
        IrString text => Quote(text.Value),
        IrConvert conversion => EmitConversion(conversion),
        IrArrayAccess access => access.Type == ValueType.String ? $"({EmitArrayAccess(access)} ?? \"\")" : EmitArrayAccess(access),
        IrVariable variable => variable.Type == ValueType.String ? $"({variable.Storage} ?? \"\")" : variable.Storage,
        IrCall call => EmitCall(call),
        IrUnary { Operator: TokenKind.Abs } unary => $"global::BB.__BlitzAbs({EmitExpression(unary.Operand)})",
        IrUnary { Operator: TokenKind.Sgn } unary => $"global::BB.__BlitzSgn({EmitExpression(unary.Operand)})",
        IrUnary unary => $"unchecked(({Operator(unary.Operator)}{EmitExpression(unary.Operand)}))",
        IrBinary binary when Operators.IsRelation(binary.Operator) => $"({EmitComparison(EmitExpression(binary.Left), binary.Left.Type, binary.Operator, EmitExpression(binary.Right))} ? 1 : 0)",
        IrBinary binary when binary.Operator == TokenKind.Power => $"((float)System.Math.Pow({EmitExpression(binary.Left)}, {EmitExpression(binary.Right)}))",
        IrBinary binary when binary.Operator == TokenKind.Shr => $"unchecked((int)((uint){EmitExpression(binary.Left)} >> {EmitExpression(binary.Right)}))",
        IrBinary binary when binary.Operator == TokenKind.Slash => $"({EmitExpression(binary.Left)} / {EmitExpression(binary.Right)})",
        IrBinary binary => $"unchecked(({EmitExpression(binary.Left)} {Operator(binary.Operator)} {EmitExpression(binary.Right)}))",
        _ => throw new InvalidOperationException("Unknown IR expression.")
    };

    private static string EmitStorage(IrExpression variable) => variable switch
    {
        IrVariable scalar => scalar.Storage,
        IrArrayAccess access => EmitArrayAccess(access),
        IrField field => EmitField(field),
        IrVectorAccess access => EmitVectorAccess(access),
        _ => throw new InvalidOperationException("Expected an assignable loop counter.")
    };

    private static string ObjectList(ValueType type) => $"global::__BlitzObjects.@{type.Name}";
    private static string EmitField(IrField field) => $"global::__BlitzObject.Require({EmitExpression(field.Owner)}, {Quote(field.Location)}).@{field.Name}";
    private static string EmitObject(IrObjectOperation operation) => operation.Operation switch
    {
        "null" => "null",
        "handle" => $"global::__BlitzHandles.ToHandle({EmitExpression(operation.Value!)}, {Quote(operation.Location)})",
        "fromhandle" => $"global::__BlitzHandles.FromHandle<{Primitive.CSharp(operation.Type)}>({EmitExpression(operation.Value!)})",
        "new" => $"{ObjectList(operation.Type)}.New()",
        "first" => $"{ObjectList(operation.Type)}.First()",
        "last" => $"{ObjectList(operation.Type)}.Last()",
        "after" => $"{ObjectList(operation.Type)}.Following(global::__BlitzObject.RequireReference({EmitExpression(operation.Value!)}, {Quote(operation.Location)}))",
        "before" => $"{ObjectList(operation.Type)}.Preceding(global::__BlitzObject.RequireReference({EmitExpression(operation.Value!)}, {Quote(operation.Location)}))",
        _ => throw new InvalidOperationException("Unknown object operation.")
    };

    private static string EmitVectorAccess(IrVectorAccess access) =>
        $"{EmitExpression(access.Owner)}.Element({EmitExpression(access.Index)}, {Quote(access.Location)})";

    private static string EmitArrayAccess(IrArrayAccess access) =>
        $"{access.Storage}.Element(new int[] {{ {string.Join(", ", access.Indices.Select(EmitExpression))} }}, {Quote(access.Location)})";

    private static string EmitCall(IrCall call)
    {
        var target = call.IsCSharp ? $"global::{call.Name}" : $"global::BB.@{call.Name}";
        var invocation = $"{target}({string.Join(", ", call.Arguments.Select(EmitExpression))})";
        if (call.Type == ValueType.String) return $"({invocation} ?? \"\")";
        return call.IsCSharp && call.Type == ValueType.Integer ? $"global::BB.__BlitzInteger({invocation})" : invocation;
    }

    private static string EmitConversion(IrConvert conversion)
    {
        var value = EmitExpression(conversion.Value);
        if (conversion.Target == ValueType.Float && conversion.Value.Type == ValueType.Integer) return $"((float){value})";
        var helper = conversion.Target == ValueType.Integer ? "__BlitzInteger" : conversion.Target == ValueType.Float ? "__BlitzFloat" : "__BlitzString";
        return $"global::BB.{helper}({value})";
    }

    private static string EmitComparison(string left, ValueType type, TokenKind op, string right) => type.IsObject
        ? $"{(op == TokenKind.NotEqual ? "!" : "")}global::__BlitzObject.Equal({left}, {right})" : type == ValueType.String
        ? $"System.String.CompareOrdinal({left}, {right}) {Operator(op)} 0" : $"{left} {Operator(op)} {right}";

    private static string Operator(TokenKind kind) => kind switch
    {
        TokenKind.Plus => "+", TokenKind.Minus => "-", TokenKind.Star => "*", TokenKind.Slash => "/", TokenKind.Mod => "%",
        TokenKind.And => "&", TokenKind.Or => "|", TokenKind.Xor => "^", TokenKind.Shl => "<<", TokenKind.Sar => ">>",
        TokenKind.Equal => "==", TokenKind.NotEqual => "!=", TokenKind.Less => "<", TokenKind.Greater => ">", TokenKind.LessEqual => "<=", TokenKind.GreaterEqual => ">=",
        _ => throw new InvalidOperationException("Unknown IR operator.")
    };
}
