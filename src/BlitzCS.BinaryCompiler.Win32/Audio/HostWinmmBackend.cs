using System.Collections.Concurrent;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using BlitzCS.BinaryCompiler.Runtime;

namespace BlitzCS.BinaryCompiler.Win32;

/// <summary>
/// Forwards waveOut to the host's winmm.dll (a Windows x64 process, including Wine). Nothing 32-bit is passed to the host API: the guest WAVEHDR (32 bytes) is mirrored by a native 48-byte WAVEHDR
/// per prepared header; the guest HWAVEOUT never leaves the handle table (the host HWAVEOUT is private to <see cref="HostDevice"/>); completion arrives through an internal CALLBACK_FUNCTION
/// (an [UnmanagedCallersOnly] static whose dwInstance is a device id, never a pointer), and the guest's own notification is delivered by the caller of <see cref="IWaveOutSink"/>.
/// lpData: when the guest memory is the runtime's <see cref="GuestMemory"/> the zero-extended guest address IS the host address (guest address == host address by construction, see
/// GuestMemory), and the bytes are played in place after IsMapped has validated the range; for any other <see cref="IWin32Memory"/> (tests, host tools) a native copy is made at prepare time and refreshed at every write.
/// </summary>
public sealed unsafe class HostWinmmBackend : IWaveOutBackend
{
    private const int NativeHeaderSize = 48; // 64-bit WAVEHDR: lpData 0, dwBufferLength 8, dwBytesRecorded 12, dwUser 16, dwFlags 24, dwLoops 28, lpNext 32, reserved 40
    private readonly WaveOutObserver? observer;
    private readonly Action<string>? diagnostic;

    public HostWinmmBackend(WaveOutObserver? observer = null, Action<string>? diagnostic = null)
    {
        if (!OperatingSystem.IsWindows()) throw new Win32UsageException("The HostWinmm waveOut backend needs a Windows host (winmm.dll); use BLITZCS_AUDIO=virtual or none on this OS.");
        this.observer = observer;
        this.diagnostic = diagnostic;
    }

    public string Name => "HostWinmm";
    public uint DeviceCount => waveOutGetNumDevs();
    public void Dispose() { }

    [DllImport("winmm.dll")] private static extern uint waveOutGetNumDevs();
    [DllImport("winmm.dll")] private static extern uint waveOutGetDevCapsW(nuint id, byte* caps, uint size);
    [DllImport("winmm.dll")] private static extern uint waveOutOpen(nint* hwo, nuint id, byte* format, nuint callback, nuint instance, uint flags);
    [DllImport("winmm.dll")] private static extern uint waveOutClose(nint hwo);
    [DllImport("winmm.dll")] private static extern uint waveOutPrepareHeader(nint hwo, byte* header, uint size);
    [DllImport("winmm.dll")] private static extern uint waveOutUnprepareHeader(nint hwo, byte* header, uint size);
    [DllImport("winmm.dll")] private static extern uint waveOutWrite(nint hwo, byte* header, uint size);
    [DllImport("winmm.dll")] private static extern uint waveOutReset(nint hwo);
    [DllImport("winmm.dll")] private static extern uint waveOutPause(nint hwo);
    [DllImport("winmm.dll")] private static extern uint waveOutRestart(nint hwo);
    [DllImport("winmm.dll")] private static extern uint waveOutBreakLoop(nint hwo);
    [DllImport("winmm.dll")] private static extern uint waveOutGetPosition(nint hwo, byte* mmt, uint size);
    [DllImport("winmm.dll")] private static extern uint waveOutGetVolume(nint hwo, uint* volume);
    [DllImport("winmm.dll")] private static extern uint waveOutSetVolume(nint hwo, uint volume);
    [DllImport("winmm.dll")] private static extern uint waveOutGetID(nint hwo, uint* id);
    [DllImport("winmm.dll", CharSet = CharSet.Unicode)] private static extern uint waveOutGetErrorTextW(uint error, char* text, uint size);

    public uint GetCaps(uint deviceId, out WaveOutCaps? caps)
    {
        var buf = stackalloc byte[WaveOutConst.CapsSizeW];
        var r = waveOutGetDevCapsW(deviceId, buf, WaveOutConst.CapsSizeW);
        caps = r == 0 ? WaveOutCaps.FromWide(new ReadOnlySpan<byte>(buf, WaveOutConst.CapsSizeW)) : null;
        return r;
    }

    public uint GetVolume(uint deviceId, out uint volume)
    {
        uint v = 0;
        var r = waveOutGetVolume((nint)deviceId, &v); // an id may be passed where an HWAVEOUT is expected (documented)
        volume = v;
        return r;
    }

    public uint SetVolume(uint deviceId, uint volume) => waveOutSetVolume((nint)deviceId, volume);

    public string? GetErrorText(uint code)
    {
        var buf = stackalloc char[256];
        return waveOutGetErrorTextW(code, buf, 256) == 0 ? new string(buf) : null;
    }

    // ---- open / completion routing ----

    private static readonly ConcurrentDictionary<nuint, HostDevice> Devices = new();
    private static long nextInstance;

    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvStdcall)])]
    private static void Callback(nint hwo, uint message, nuint instance, nuint param1, nuint param2)
    {
        // Runs on a winmm thread. WOM_OPEN/WOM_CLOSE are generated by the caller of the sink; only WOM_DONE matters here. Nothing may escape.
        if (message != WaveOutConst.WomDone || !Devices.TryGetValue(instance, out var device)) return;
        try { device.OnDone((nint)param1); }
        catch (Exception e) { device.RecordFault(e); }
    }

    public uint Open(uint deviceId, WaveOutFormat format, uint flags, IWaveOutSink sink, out IWaveOutDevice? device)
    {
        device = null;
        var query = (flags & WaveOutConst.WaveFormatQuery) != 0;
        var native = (byte*)NativeMemory.Alloc((nuint)format.Raw.Length);
        try
        {
            format.Raw.CopyTo(new Span<byte>(native, format.Raw.Length));
            var hostFlags = flags & (WaveOutConst.WaveFormatQuery | WaveOutConst.WaveAllowSync | WaveOutConst.WaveFormatDirect | WaveOutConst.WaveMappedDefaultCommunicationDevice);
            if (query) return waveOutOpen(null, deviceId, native, 0, 0, hostFlags);
            var dev = new HostDevice(this, format, sink);
            var instance = (nuint)Interlocked.Increment(ref nextInstance);
            Devices[instance] = dev;
            nint hwo = 0;
            var cb = (nuint)(delegate* unmanaged[Stdcall]<nint, uint, nuint, nuint, nuint, void>)&Callback;
            var r = waveOutOpen(&hwo, deviceId, native, cb, instance, hostFlags | WaveOutConst.CallbackFunction);
            if (r != 0) { Devices.TryRemove(instance, out _); return r; }
            uint id = deviceId;
            if (waveOutGetID(hwo, &id) != 0) id = deviceId;
            dev.Attach(hwo, instance, id);
            device = dev;
            return 0;
        }
        finally { NativeMemory.Free(native); }
    }

    private sealed class NativeHeader
    {
        public nint Header;
        public nint Shadow;
        public bool InPlace;
    }

    private sealed class HostDevice(HostWinmmBackend owner, WaveOutFormat format, IWaveOutSink sink) : IWaveOutDevice
    {
        private nint hwo;
        private nuint instance;
        private int closed;
        private readonly ConcurrentDictionary<nint, WaveOutBuffer> byNative = new();
        private readonly System.Diagnostics.Stopwatch clock = System.Diagnostics.Stopwatch.StartNew();
        private readonly ConcurrentQueue<Exception> faults = new();

        public uint DeviceId { get; private set; }

        public void Attach(nint handle, nuint id, uint device) { hwo = handle; instance = id; DeviceId = device; }
        public void RecordFault(Exception e) { faults.Enqueue(e); owner.diagnostic?.Invoke("HostWinmm callback fault: " + e); }

        public void OnDone(nint nativeHeader)
        {
            if (byNative.TryGetValue(nativeHeader, out var buffer)) sink.BufferDone(buffer);
        }

        private static bool InPlace(WaveOutBuffer b) => b.Memory is GuestMemoryAdapter;

        public uint Prepare(WaveOutBuffer b)
        {
            var inPlace = InPlace(b);
            if (!b.Memory.IsMapped(b.DataAddress, b.PreparedLength)) return WaveOutConst.MmsyserrInvalParam;
            var st = new NativeHeader { Header = (nint)NativeMemory.AllocZeroed(NativeHeaderSize), InPlace = inPlace };
            st.Shadow = inPlace ? 0 : (nint)NativeMemory.AllocZeroed(Math.Max(b.PreparedLength, 1));
            var h = (byte*)st.Header;
            *(nint*)h = inPlace ? (nint)b.DataAddress : st.Shadow;
            *(uint*)(h + 8) = b.PreparedLength;
            var r = waveOutPrepareHeader(hwo, h, NativeHeaderSize);
            if (r != 0) { Free(st); return r; }
            b.BackendState = st;
            byNative[st.Header] = b;
            return 0;
        }

        private static void Free(NativeHeader st)
        {
            NativeMemory.Free((void*)st.Header);
            if (st.Shadow != 0) NativeMemory.Free((void*)st.Shadow);
        }

        public uint Unprepare(WaveOutBuffer b)
        {
            if (b.BackendState is not NativeHeader st) return WaveOutConst.WaverrUnprepared;
            var r = waveOutUnprepareHeader(hwo, (byte*)st.Header, NativeHeaderSize);
            if (r != 0) return r;
            byNative.TryRemove(st.Header, out _);
            b.BackendState = null;
            Free(st);
            return 0;
        }

        public uint Write(WaveOutBuffer b)
        {
            if (b.BackendState is not NativeHeader st) return WaveOutConst.WaverrUnprepared;
            if (b.Length > b.PreparedLength) return WaveOutConst.MmsyserrInvalParam;
            byte[]? data = null;
            try
            {
                if (!st.InPlace || owner.observer is not null) data = b.ReadData();
                if (!st.InPlace) Marshal.Copy(data!, 0, st.Shadow, data!.Length);
            }
            catch (GuestMemoryException) { return WaveOutConst.MmsyserrInvalParam; }
            var h = (byte*)st.Header;
            *(uint*)(h + 8) = b.Length;
            *(nuint*)(h + 16) = b.User;
            *(uint*)(h + 28) = b.Loops;
            var loopMask = WaveOutConst.WhdrBeginLoop | WaveOutConst.WhdrEndLoop;
            *(uint*)(h + 24) = (*(uint*)(h + 24) & ~loopMask) | (b.Flags & loopMask);
            if (owner.observer is { } obs && data is not null)
                obs(new WaveOutWrite(DeviceId, b.HeaderAddress, format, clock.ElapsedMilliseconds, data));
            return waveOutWrite(hwo, h, NativeHeaderSize);
        }

        public uint Reset() => waveOutReset(hwo);
        public uint Pause() => waveOutPause(hwo);
        public uint Restart() => waveOutRestart(hwo);
        public uint BreakLoop() => waveOutBreakLoop(hwo);

        public uint GetPosition(uint type, out uint typeReturned, out uint value)
        {
            var mmt = stackalloc byte[WaveOutConst.MmTimeSize];
            new Span<byte>(mmt, WaveOutConst.MmTimeSize).Clear();
            *(uint*)mmt = type;
            var r = waveOutGetPosition(hwo, mmt, WaveOutConst.MmTimeSize);
            typeReturned = *(uint*)mmt;
            value = *(uint*)(mmt + 4);
            return r;
        }

        public uint GetVolume(out uint volume)
        {
            uint v = 0;
            var r = waveOutGetVolume(hwo, &v);
            volume = v;
            return r;
        }

        public uint SetVolume(uint volume) => waveOutSetVolume(hwo, volume);

        public uint Close()
        {
            var r = waveOutClose(hwo);
            if (r == 0) Release();
            return r;
        }

        private void Release()
        {
            if (Interlocked.Exchange(ref closed, 1) != 0) return;
            Devices.TryRemove(instance, out _);
            foreach (var kv in byNative) if (kv.Value.BackendState is NativeHeader st) { Free(st); kv.Value.BackendState = null; }
            byNative.Clear();
        }

        public void Dispose()
        {
            if (Volatile.Read(ref closed) != 0) return;
            waveOutReset(hwo);
            foreach (var kv in byNative) if (kv.Value.BackendState is NativeHeader st) waveOutUnprepareHeader(hwo, (byte*)st.Header, NativeHeaderSize);
            waveOutClose(hwo);
            Release();
        }
    }
}
