"""Generate explicit numeric bindings to the original runtime; no engine implementation."""
import argparse
import json
from pathlib import Path
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail if generated files are stale')
options = parser.parse_args()
root = Path(__file__).resolve().parents[2]
provider = Path(__file__).resolve().parent
profile = json.loads((root / 'profiles/blitz3d.json').read_text())
functions = []
methods = []
clr = {'Integer': 'int', 'Float': 'float', 'Void': 'void'}
for f in profile['functions']:
    types = f['parameters']
    result = f['returnType']
    if any(t not in ('Integer', 'Float') for t in types) or result not in clr:
        continue
    name = f['name']
    # Process termination must return through Runtime::execute, not throw native exceptions across CLR frames.
    if name.lower() in ('runtimeerror', 'stop', 'debugstop'):
        continue
    args = ', '.join(f'{clr[t]} p{i}' for i, t in enumerate(types))
    values = ', '.join(f'p{i}' for i in range(len(types)))
    types_cs = ', '.join(json.dumps(t) for t in types)
    invocation = f'Call("{name}", "{result}", [{types_cs}], [{values}])'
    statement = invocation + ';' if result == 'Void' else f'return ({clr[result]}){invocation}!;'
    methods.append(f'    public static {clr[result]} {name}({args}) {{ {statement} }}')
    functions.append(dict(name=name, assembly='Bridge/bin/Release/net10.0/BlitzCS.OriginalRuntime.Bridge.dll', type='BlitzCS.OriginalRuntime.Commands', method=name, parameters=types, returnType=result))
outputs = {
    provider / 'Bridge/Commands.Generated.cs': '// Generated by ../generate.py from the historical API profile.\nnamespace BlitzCS.OriginalRuntime;\npublic static partial class Commands\n{\n' + '\n'.join(methods) + '\n}\n',
    provider / 'runtime.json': json.dumps(dict(profiles=['../../profiles/blitz3d.json'], functions=functions), indent=2) + '\n',
}
for path, text in outputs.items():
    if options.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('Stale generated file: ' + path.name)
    else:
        path.write_text(text)
print(f'{len(functions)} numeric bindings ' + ('verified' if options.check else 'generated'))
