"""Generate explicit bindings to the original runtime; no engine implementation."""
import argparse
import json
from pathlib import Path
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail if generated files are stale')
options = parser.parse_args()
root = Path(__file__).resolve().parents[2]
provider = Path(__file__).resolve().parent
profile = json.loads((root / 'profiles/blitz3d.json').read_text())
overlay = json.loads((root / 'profiles/scpcb-mavless.json').read_text())
functions = []
fork_functions = []
methods = []
names = []
clr = {'Integer': 'int', 'Float': 'float', 'Void': 'void', 'String': 'string'}
for f in profile['functions'] + overlay['functions']:
    types = f['parameters']
    result = f['returnType']
    if any(t not in ('Integer', 'Float', 'String') for t in types) or result not in clr:
        continue
    name = f['name']
    # Process termination must return through Runtime::execute, not throw native exceptions across CLR frames.
    if name.lower() in ('runtimeerror', 'stop', 'debugstop'):
        continue
    args = ', '.join(f'{clr[t]} p{i}' for i, t in enumerate(types))
    values = ', '.join(f'p{i}' for i in range(len(types)))
    types_cs = ', '.join(json.dumps(t) for t in types)
    invocation = f'Call("{name}", "{result}", [{types_cs}], [{values}])'
    statement = invocation + ';' if result == 'Void' else f'return ({clr[result]}){invocation}!;'
    index = len(names)
    names.append(name)
    native = {'Integer': 'int', 'Float': 'float', 'Void': 'void', 'String': 'nint'}
    native_types = ', '.join([native[t] for t in types] + [native[result]])
    string_indices = [i for i, t in enumerate(types) if t == 'String']
    native_values = ', '.join(f's{i}' if t == 'String' else f'p{i}' for i, t in enumerate(types))
    direct = f'((delegate* unmanaged[Stdcall]<{native_types}>)pointer)({native_values})'
    direct_statement = direct + ';' if result == 'Void' else 'return ' + (f'session.FromNativeString({direct})' if result == 'String' else direct) + ';'
    slow_statement = statement + (' return;' if result == 'Void' else '')
    body = [f'        {direct_statement}']
    if string_indices:
        body = [f'        nint s{i} = 0;' for i in string_indices]
        body += ['        bool transferred = false;', '        try', '        {']
        body += [f'            s{i} = session.ToNativeString(p{i});' for i in string_indices]
        body += ['            transferred = true;', f'            {direct_statement}', '        }', '        finally', '        {', '            if (!transferred)', '            {']
        body += [f'                if (s{i} != 0) session.Release(s{i});' for i in string_indices]
        body += ['            }', '        }']
    methods.append(f'''    public static unsafe {clr[result]} {name}({args})
    {{
        var session = Current;
        if (session.Traced[{index}]) {{ {slow_statement} }}
        var pointer = session.Pointers[{index}];
        if (pointer == 0) pointer = session.Resolve({index}, "{name}", "{result}", [{types_cs}]);
''' + '\n'.join(body) + '\n    }')
    target = fork_functions if f in overlay['functions'] else functions
    target.append(dict(name=name, assembly='Bridge/bin/Release/net10.0/BlitzCS.OriginalRuntime.Bridge.dll', type='BlitzCS.OriginalRuntime.Commands', method=name, parameters=types, returnType=result))
outputs = {
    provider / 'Bridge/Commands.Generated.cs': '// Generated by ../generate.py from the historical API profile.\nnamespace BlitzCS.OriginalRuntime;\npublic static partial class Commands\n{\n' + '    private static readonly string[] CommandNames = [' + ', '.join(json.dumps(n) for n in names) + '];\n' + '\n'.join(methods) + '\n}\n',
    provider / 'runtime.json': json.dumps(dict(profiles=['../../profiles/blitz3d.json'], functions=functions), indent=2) + '\n',
    provider / 'scpcb-runtime.json': json.dumps(dict(profiles=['runtime.json', '../../profiles/scpcb-mavless.json'], functions=fork_functions), indent=2) + '\n',
}
for path, text in outputs.items():
    if options.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('Stale generated file: ' + path.name)
    else:
        path.write_text(text)
print(f'{len(functions)} stock and {len(fork_functions)} fork bindings ' + ('verified' if options.check else 'generated'))
